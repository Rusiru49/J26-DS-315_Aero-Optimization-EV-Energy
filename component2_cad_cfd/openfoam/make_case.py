#!/usr/bin/env python3
"""Create one OpenFOAM (ESI, v2512/v2606 style) case for one sedan design.
Pure python3 - no extra packages.
usage: python3 make_case.py --stl sedan_D000.stl --design D000 --speed 27.78 --aref 2.1812 --mesh medium --np 6 --out cases
Car frame in Fusion: nose Z=0, tail Z=-4800, X lateral, Y up, mm.
OpenFOAM frame      : x = -Z (flow ->), y = -X, z = Y (up), metres.
"""
import argparse, os, struct, math, re

RHO = 1.165          # kg/m3  Sri Lanka air (from project spec)
MU  = 1.86e-5        # Pa s
NU  = MU / RHO       # m2/s
L   = 4.8            # car length m
MESH_DX = {"coarse": 0.52, "medium": 0.40, "fine": 0.31}   # background cell size (m), ratio ~1.3 for GCI

def read_stl(path):
    data = open(path, "rb").read()
    if data[:5] == b"solid" and b"facet" in data[:400]:     # ASCII
        vs = re.findall(rb"vertex\s+(\S+)\s+(\S+)\s+(\S+)", data)
        v = [tuple(float(a) for a in t) for t in vs]
        return [v[i:i+3] for i in range(0, len(v), 3)]
    n = struct.unpack("<I", data[80:84])[0]
    tris = []
    for i in range(n):
        o = 84 + 50*i
        f = struct.unpack("<12f", data[o:o+48])
        tris.append([f[3:6], f[6:9], f[9:12]])
    return tris

def to_foam(p):             # mm Fusion -> m OpenFOAM
    X, Y, Z = p
    return (-Z/1000.0, -X/1000.0, Y/1000.0)

def write_stl(tris, path):
    with open(path, "w") as f:
        f.write("solid car\n")
        for t in tris:
            a, b, c = t
            ux, uy, uz = (b[i]-a[i] for i in range(3)); vx, vy, vz = (c[i]-a[i] for i in range(3))
            n = (uy*vz-uz*vy, uz*vx-ux*vz, ux*vy-uy*vx); m = math.sqrt(sum(x*x for x in n)) or 1.0
            f.write(" facet normal %.6g %.6g %.6g\n  outer loop\n" % (n[0]/m, n[1]/m, n[2]/m))
            for p in t: f.write("   vertex %.6f %.6f %.6f\n" % p)
            f.write("  endloop\n endfacet\n")
        f.write("endsolid car\n")

HDR = """FoamFile
{
    version 2.0;
    format  ascii;
    class   %s;
    object  %s;
}
"""
def w(path, cls, obj, body):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w").write("/* generated by make_case.py */\n" + HDR % (cls, obj) + body)

def tpl(s, **kw):
    for k, v in kw.items(): s = s.replace("@%s@" % k, str(v))
    return s

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stl", required=True); ap.add_argument("--design", required=True)
    ap.add_argument("--speed", type=float, required=True)
    ap.add_argument("--aref", type=float, required=True, help="FULL-car frontal area m2 (A_frontal_m2 from design table)")
    ap.add_argument("--mesh", default="medium", choices=list(MESH_DX))
    ap.add_argument("--full", action="store_true", help="simulate the full car (default: half car with symmetry plane)")
    ap.add_argument("--np", type=int, default=6); ap.add_argument("--out", default="cases")
    ap.add_argument("--iters", type=int, default=1500); ap.add_argument("--avg", type=int, default=100)
    a = ap.parse_args()
    half = not a.full
    U = a.speed
    name = "%s_%s_%s" % (a.design, ("%dkmh" % round(U*3.6)), a.mesh)
    case = os.path.join(a.out, name)

    tris = [[to_foam(p) for p in t] for t in read_stl(a.stl)]
    os.makedirs(os.path.join(case, "constant", "triSurface"), exist_ok=True)
    write_stl(tris, os.path.join(case, "constant", "triSurface", "car.stl"))
    xs = [p[0] for t in tris for p in t]; ys = [p[1] for t in tris for p in t]; zs = [p[2] for t in tris for p in t]
    xmin, xmax, ymin, ymax, zmin, zmax = min(xs), max(xs), min(ys), max(ys), min(zs), max(zs)

    # ---- domain: 2L in front, 5L behind, 3L to the side and top
    X0, X1 = xmin - 2*L, xmax + 5*L
    Y1 = 3*L; Y0 = 0.0 if half else -Y1
    Z0, Z1 = 0.0, 3*L
    dx = MESH_DX[a.mesh]
    nx = round((X1-X0)/dx); ny = round((Y1-Y0)/dx); nz = round((Z1-Z0)/dx)
    verts = [(X0,Y0,Z0),(X1,Y0,Z0),(X1,Y1,Z0),(X0,Y1,Z0),(X0,Y0,Z1),(X1,Y0,Z1),(X1,Y1,Z1),(X0,Y1,Z1)]
    vtxt = "\n".join("    (%.4f %.4f %.4f)" % v for v in verts)
    sides = "            (3 7 6 2)" + ("" if half else "\n            (0 1 5 4)")
    symm = ("    symm\n    {\n        type symmetryPlane;\n        faces\n        (\n            (0 1 5 4)\n        );\n    }\n" if half else "")
    w(case+"/system/blockMeshDict", "dictionary", "blockMeshDict", tpl("""
convertToMeters 1;
vertices
(
@V@
);
blocks ( hex (0 1 2 3 4 5 6 7) (@NX@ @NY@ @NZ@) simpleGrading (1 1 1) );
edges ();
boundary
(
    inlet   { type patch; faces ( (0 4 7 3) ); }
    outlet  { type patch; faces ( (1 2 6 5) ); }
    ground  { type wall;  faces ( (0 3 2 1) ); }
    top     { type patch; faces ( (4 5 6 7) ); }
    sides   { type patch; faces (
@S@
    ); }
@SY@
);
mergePatchPairs ();
""", V=vtxt, NX=nx, NY=ny, NZ=nz, S=sides, SY=("    symm { type symmetryPlane; faces ( (0 1 5 4) ); }" if half else "")))

    # ---- feature edges
    w(case+"/system/surfaceFeaturesDict", "dictionary", "surfaceFeaturesDict", """
surfaces ("car.stl");
includedAngle 150;
subsetFeatures { nonManifoldEdges no; openEdges yes; }
writeObj no;
""")

    # older/alternative tool name (this is the one that exists in OpenFOAM v2606 on macOS)
    w(case+"/system/surfaceFeatureExtractDict", "dictionary", "surfaceFeatureExtractDict", """
car.stl
{
    extractionMethod    extractFromSurface;
    extractFromSurfaceCoeffs { includedAngle 150; }
    subsetFeatures { nonManifoldEdges no; openEdges yes; }
    writeObj            no;
}
""")

    # ---- snappyHexMesh
    bx = (xmin-0.5, (0.0 if half else ymin-0.5), 0.0, xmax+0.5, ymax+0.5, zmax+0.5)
    wk = (xmax-0.5, (0.0 if half else ymin-0.6), 0.0, xmax+6.0, ymax+0.6, zmax+0.8)
    loc = (X0 + 4.9371*1.0, 3.0113, 2.9487)
    w(case+"/system/snappyHexMeshDict", "dictionary", "snappyHexMeshDict", tpl("""
castellatedMesh true;
snap            true;
addLayers       true;
geometry
{
    car.stl { type triSurfaceMesh; name car; }
    refBox  { type searchableBox; min (@B0@ @B1@ @B2@); max (@B3@ @B4@ @B5@); }
    wakeBox { type searchableBox; min (@W0@ @W1@ @W2@); max (@W3@ @W4@ @W5@); }
}
castellatedMeshControls
{
    maxLocalCells 4000000;
    maxGlobalCells 6000000;
    minRefinementCells 10;
    maxLoadUnbalance 0.10;
    nCellsBetweenLevels 3;
    features ( { file "car.eMesh"; level 5; } );
    refinementSurfaces { car { level (4 5); patchInfo { type wall; } } }
    resolveFeatureAngle 30;
    refinementRegions
    {
        refBox  { mode inside; levels ((1E15 3)); }
        wakeBox { mode inside; levels ((1E15 2)); }
    }
    locationInMesh (@LX@ @LY@ @LZ@);
    allowFreeStandingZoneFaces true;
}
snapControls
{
    nSmoothPatch 3; tolerance 2.0; nSolveIter 50; nRelaxIter 5;
    nFeatureSnapIter 10; implicitFeatureSnap false; explicitFeatureSnap true; multiRegionFeatureSnap false;
}
addLayersControls
{
    relativeSizes true;
    layers { "car.*" { nSurfaceLayers 4; } }
    expansionRatio 1.2;
    finalLayerThickness 0.5;
    minThickness 0.05;
    nGrow 0;
    featureAngle 130;
    slipFeatureAngle 30;
    nRelaxIter 5;
    nSmoothSurfaceNormals 1;
    nSmoothNormals 3;
    nSmoothThickness 10;
    maxFaceThicknessRatio 0.5;
    maxThicknessToMedialRatio 0.3;
    minMedialAxisAngle 90;
    nBufferCellsNoExtrude 0;
    nLayerIter 50;
    nRelaxedIter 20;
}
meshQualityControls
{
    maxNonOrtho 65; maxBoundarySkewness 20; maxInternalSkewness 4; maxConcave 80;
    minVol 1e-13; minTetQuality 1e-15; minArea -1; minTwist 0.02; minDeterminant 0.001;
    minFaceWeight 0.05; minVolRatio 0.01; minTriangleTwist -1; nSmoothScale 4; errorReduction 0.75;
    relaxed { maxNonOrtho 75; }
}
mergeTolerance 1e-6;
debug 0;
""", B0="%.3f"%bx[0],B1="%.3f"%bx[1],B2="%.3f"%bx[2],B3="%.3f"%bx[3],B4="%.3f"%bx[4],B5="%.3f"%bx[5],
     W0="%.3f"%wk[0],W1="%.3f"%wk[1],W2="%.3f"%wk[2],W3="%.3f"%wk[3],W4="%.3f"%wk[4],W5="%.3f"%wk[5],
     LX="%.4f"%loc[0],LY=loc[1],LZ=loc[2]))

    # ---- physics
    w(case+"/constant/transportProperties", "dictionary", "transportProperties", "transportModel Newtonian;\nnu %.6e;\n" % NU)
    w(case+"/constant/turbulenceProperties", "dictionary", "turbulenceProperties",
      "simulationType RAS;\nRAS\n{\n    model kOmegaSST;\n    RASModel kOmegaSST;\n    turbulence on;\n    printCoeffs on;\n}\n")

    # ---- run control + function objects
    aref = a.aref/2.0 if half else a.aref
    w(case+"/system/controlDict", "dictionary", "controlDict", tpl("""
application     simpleFoam;
startFrom       startTime;
startTime       0;
stopAt          endTime;
endTime         @END@;
deltaT          1;
writeControl    timeStep;
writeInterval   @END@;
purgeWrite      1;
writeFormat     binary;
writePrecision  8;
timeFormat      general;
timePrecision   6;
runTimeModifiable false;

functions
{
    forceCoeffs1
    {
        type            forceCoeffs;
        libs            ("libforces.so");
        writeControl    timeStep;
        writeInterval   1;
        patches         ("car.*");
        rho             rhoInf;
        rhoInf          @RHO@;
        liftDir         (0 0 1);
        dragDir         (1 0 0);
        CofR            (@CX@ 0 0.3);
        pitchAxis       (0 1 0);
        magUInf         @U@;
        lRef            @L@;
        Aref            @AREF@;
    }
    wallShearStress1
    {
        type            wallShearStress;
        libs            ("libfieldFunctionObjects.so");
        writeControl    writeTime;
        patches         ("car.*");
    }
    yPlus1
    {
        type            yPlus;
        libs            ("libfieldFunctionObjects.so");
        writeControl    writeTime;
    }
    fieldAverage1
    {
        type            fieldAverage;
        libs            ("libfieldFunctionObjects.so");
        writeControl    writeTime;
        timeStart       @TS@;
        fields
        (
            p                { mean on; prime2Mean off; base time; }
            U                { mean on; prime2Mean off; base time; }
            wallShearStress  { mean on; prime2Mean off; base time; }
        );
    }
}
""", END=a.iters, RHO=RHO, U=U, L=L, AREF="%.5f"%aref, CX="%.2f"%((xmin+xmax)/2), TS=a.iters-a.avg))

    w(case+"/system/fvSchemes", "dictionary", "fvSchemes", """
ddtSchemes { default steadyState; }
gradSchemes { default Gauss linear; limited cellLimited Gauss linear 1; grad(U) $limited; grad(k) $limited; grad(omega) $limited; }
divSchemes
{
    default none;
    div(phi,U)      bounded Gauss linearUpwind limited;
    div(phi,k)      bounded Gauss upwind;
    div(phi,omega)  bounded Gauss upwind;
    div((nuEff*dev2(T(grad(U))))) Gauss linear;
}
laplacianSchemes { default Gauss linear corrected; }
interpolationSchemes { default linear; }
snGradSchemes { default corrected; }
wallDist { method meshWave; }
""")
    w(case+"/system/fvSolution", "dictionary", "fvSolution", """
solvers
{
    p { solver GAMG; smoother GaussSeidel; tolerance 1e-8; relTol 0.1; }
    "(U|k|omega)" { solver smoothSolver; smoother symGaussSeidel; tolerance 1e-9; relTol 0.1; }
}
SIMPLE
{
    nNonOrthogonalCorrectors 1;
    consistent yes;
    pRefCell 0;
    pRefValue 0;
}
relaxationFactors
{
    equations { U 0.9; ".*" 0.9; }
}
""")
    w(case+"/system/decomposeParDict", "dictionary", "decomposeParDict",
      "numberOfSubdomains %d;\nmethod scotch;\n" % a.np)

    # ---- initial / boundary conditions
    I = 0.01
    k = 1.5*(I*U)**2
    omega = k/(NU*10.0)          # turbulent viscosity ratio 10
    def field(cls, obj, dims, internal, bc):
        w(case+"/0/"+obj, cls, obj, "dimensions [%s];\ninternalField uniform %s;\nboundaryField\n{\n%s}\n" % (dims, internal, bc))
    symmbc = "    symm { type symmetryPlane; }\n" if half else ""
    field("volVectorField", "U", "0 1 -1 0 0 0 0", "(%.4f 0 0)" % U,
      "    inlet  { type fixedValue; value uniform (%.4f 0 0); }\n"
      "    outlet { type inletOutlet; inletValue uniform (0 0 0); value uniform (%.4f 0 0); }\n"
      "    ground { type fixedValue; value uniform (%.4f 0 0); }\n"
      "    top    { type slip; }\n    sides  { type slip; }\n%s"
      "    \"car.*\" { type noSlip; }\n" % (U, U, U, symmbc))
    field("volScalarField", "p", "0 2 -2 0 0 0 0", "0",
      "    inlet  { type zeroGradient; }\n    outlet { type fixedValue; value uniform 0; }\n"
      "    ground { type zeroGradient; }\n    top    { type slip; }\n    sides  { type slip; }\n%s"
      "    \"car.*\" { type zeroGradient; }\n" % symmbc)
    field("volScalarField", "k", "0 2 -2 0 0 0 0", "%.6g" % k,
      "    inlet  { type fixedValue; value uniform %.6g; }\n    outlet { type inletOutlet; inletValue uniform %.6g; value uniform %.6g; }\n"
      "    ground { type kqRWallFunction; value uniform %.6g; }\n    top    { type slip; }\n    sides  { type slip; }\n%s"
      "    \"car.*\" { type kqRWallFunction; value uniform %.6g; }\n" % (k,k,k,k,symmbc,k))
    field("volScalarField", "omega", "0 0 -1 0 0 0 0", "%.6g" % omega,
      "    inlet  { type fixedValue; value uniform %.6g; }\n    outlet { type inletOutlet; inletValue uniform %.6g; value uniform %.6g; }\n"
      "    ground { type omegaWallFunction; value uniform %.6g; }\n    top    { type slip; }\n    sides  { type slip; }\n%s"
      "    \"car.*\" { type omegaWallFunction; value uniform %.6g; }\n" % (omega,omega,omega,omega,symmbc,omega))
    field("volScalarField", "nut", "0 2 -1 0 0 0 0", "0",
      "    inlet  { type calculated; value uniform 0; }\n    outlet { type calculated; value uniform 0; }\n"
      "    ground { type nutkWallFunction; value uniform 0; }\n    top    { type slip; }\n    sides  { type slip; }\n%s"
      "    \"car.*\" { type nutkWallFunction; value uniform 0; }\n" % symmbc)

    # ---- one-shot run script for this case
    open(case+"/Allrun", "w").write("""#!/bin/bash
# run inside an OpenFOAM terminal.   usage: ./Allrun [NP]
cd "$(dirname "$0")"
NP=${1:-@NP@}
set -e
for t in blockMesh snappyHexMesh checkMesh simpleFoam foamToVTK; do
    command -v $t >/dev/null 2>&1 || { echo "MISSING TOOL: $t  (tell Claude)"; exit 1; }
done
if command -v surfaceFeatures >/dev/null 2>&1; then
    surfaceFeatures                > log.surfaceFeatures 2>&1
elif command -v surfaceFeatureExtract >/dev/null 2>&1; then
    surfaceFeatureExtract          > log.surfaceFeatures 2>&1
else
    echo "WARNING: no surfaceFeatures tool found - continuing without feature edges"
    sed -i.bak 's/features ( { file "car.eMesh"; level 5; } );/features ();/' system/snappyHexMeshDict
fi
echo "step 1/6 features done"
blockMesh                          > log.blockMesh 2>&1
echo "step 2/6 blockMesh done"
snappyHexMesh -overwrite           > log.snappyHexMesh 2>&1
echo "step 3/6 snappyHexMesh done"
checkMesh -allGeometry -allTopology > log.checkMesh 2>&1 || true
echo "step 4/6 checkMesh done"
if [ "$NP" -gt 1 ] && command -v mpirun >/dev/null 2>&1; then
    decomposePar -force            > log.decomposePar 2>&1
    mpirun -np $NP simpleFoam -parallel > log.simpleFoam 2>&1 || echo "NOTE: mpirun returned non-zero; checking whether the run finished"
    ENDT=$(grep -m1 -E "^endTime" system/controlDict | awk '{print $2}' | tr -d ";")
    if [ ! -d "processor0/$ENDT" ]; then echo "SOLVER FAILED: processor0/$ENDT missing - see log.simpleFoam"; exit 1; fi
    reconstructPar -latestTime     > log.reconstructPar 2>&1
    rm -rf processor*
else
    simpleFoam                     > log.simpleFoam 2>&1
fi
echo "step 5/6 solver done"
PATCH=$(awk '/^ *car[A-Za-z0-9_]* *$/ {print $1; exit}' constant/polyMesh/boundary)
echo "$PATCH" > car_patch_name.txt
foamToVTK -ascii -latestTime -patches "($PATCH)" > log.foamToVTK 2>&1
echo "step 6/6 export done"
echo DONE
""".replace("@NP@", str(a.np)))
    os.chmod(case+"/Allrun", 0o755)
    open(case+"/case_info.txt", "w").write(
        "design %s\nspeed_m_s %s\nmesh %s\nhalf_model %s\nAref_used %.5f\nAref_full %.5f\nrho %s\nnu %.6e\nbase_cells %dx%dx%d\n"
        % (a.design, U, a.mesh, half, aref, a.aref, RHO, NU, nx, ny, nz))
    print("created", case, "background cells", nx*ny*nz, "bbox x[%.2f,%.2f] y[%.2f,%.2f] z[%.2f,%.2f]" % (xmin,xmax,ymin,ymax,zmin,zmax))

if __name__ == "__main__":
    main()
